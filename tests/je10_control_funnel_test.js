'use strict';
const assert=require('node:assert/strict');
const {ControlFunnel}=require('../scripts/je10_control_funnel');
const snap=(trap=[0,0],alive=[true,true])=>({trapped:trap,alive,team:[0,1],pos:[5.5,5.5,5.5,6.5]});
const info={died:[false,false],causalDamageSource:[[false,false],[true,false]],causalKill:[false,false]};
const f=new ControlFunnel(0);
f.observe(snap(),snap([0,60]),info);
f.observe(snap([0,60]),snap([0,59]),info);
assert.equal(f.metrics.attributed_first_control,1);
f.observe(snap([0,59]),snap([0,0],[true,false]),{...info,died:[false,true],causalDamageSource:[[false,false],[false,false]]});
assert.equal(f.metrics.causal_kill,1,'native contact death retains original control ownership');
assert.equal(f.metrics.surviving_kill,1);
assert.equal(f.metrics.active_contact_pop,1);
assert.equal(f.metrics.native_causal_kill,0);
const g=new ControlFunnel(0);
g.observe(snap(),snap([0,1]),info);
g.observe(snap([0,1]),snap([0,0],[true,false]),{...info,died:[false,true]});
assert.equal(g.metrics.final_pop,1);assert.equal(g.metrics.active_contact_pop,0,'timeout is not active trigger credit');
const h=new ControlFunnel(0);
h.observe(snap(),snap([0,60]),{...info,causalDamageSource:[[false,false],[true,true]]});
h.observe(snap([0,60]),snap([0,0],[true,false]),{...info,died:[false,true]});
assert.equal(h.metrics.attributed_first_control,0);assert.equal(h.metrics.causal_kill,0,'ambiguous original source remains uncredited');
console.log('JE10 passive control funnel ownership, survival, active/timeout and ambiguity passed');
