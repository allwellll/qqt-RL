'use strict';
const assert = require('assert');
const fs = require('fs');
const Q = require('./sim-bun-native-v4-facing.js');
const levels = require('./assets/maps/levels.json');
const level = levels.find(row => row.qqt_id === 806);
assert(level, 'training map 806 is required');
const sim = new Q.Sim(0x4b494c4c);
sim.reset(level, { nativeItems: true, nativeTrap: true, killMode: true, teams: [0, 1] });
assert.equal(sim.killMode, true);
assert.equal(sim.isBun, false, 'kill mode must not initialize bun delivery');
assert.equal(sim.brick.reduce((n, x) => n + x, 0), 0, 'kill mode clears breakable bricks');
assert.equal(sim.crate.reduce((n, x) => n + x, 0), 0, 'kill mode starts with no cage inventory');
const deathCell = sim.centerCell(0).join(',');
sim._killPlayer(0);
assert.equal(sim.killRespawn[0], 30, 'three second respawn countdown');
for (let i = 0; i < 30; i++) sim.step([[Q.MOVE_IDLE, 0, 0, 1, -1, -1, 0], [Q.MOVE_IDLE, 0, 0, 1, -1, -1, 0]]);
assert.equal(sim.alive[0], true, 'dead player respawns');
assert.equal(sim.invuln[0], 10, 'one second spawn protection');
assert(sim.crate.reduce((n, x) => n + x, 0) >= 8, 'death releases eight recovery drops');
assert.notEqual(sim.centerCell(0).join(','), deathCell, 'respawn is a deterministic safe random cell');
const html = fs.readFileSync(`${__dirname}/index.html`, 'utf8');
assert.match(html, /id="game-mode"/);
assert.match(html, /value="kill" selected>纯击杀/);
assert.match(fs.readFileSync(`${__dirname}/app.js`, 'utf8'), /opponentSelect\.value = `\$\{MODEL_PREFIX\}\$\{defaultModelId\}`/);
console.log('kill mode: clear-map, model-default UI, 3s safe respawn, 1s protection, 8 drops PASS');
